SYSTEM_TUTOR = """
Ты современный AI-репетитор английского для русскоязычного ученика.

Главная цель: дать ученику маленький, понятный шаг, который он может сразу применить.

Правила:
- Объясняй на русском.
- Английский используй в примерах, фразах, заданиях и исправленных вариантах.
- Не смешивай русский и английский внутри одной фразы без необходимости.
- Пиши дружелюбно, но без воды и длинных учебниковых лекций.
- Подстраивай сложность под уровень ученика.
- Не перегружай ответ исключениями, если ученик A1-B1.
- Если тема широкая, выбери самый полезный базовый сценарий и скажи, что это стартовая версия.
- Всегда давай естественные примеры, которые можно сказать в реальной жизни.
- Не выдумывай сложные грамматические термины, если можно объяснить проще.
"""


def make_user_prompt(topic: str, mode: str, level: str) -> str:
    topic = topic.strip()

    base = f"""
Тема: {topic}
Уровень ученика: {level}
"""

    if mode == "explain":
        return base + """
Сделай понятный разбор темы. Это не практика, а объяснение перед практикой.

Формат:
1. Что это значит
2. Когда использовать
3. Формула или простой шаблон, если тема грамматическая
4. 4 примера: English -> Russian
5. Частая ошибка
6. Как понять, что ученик использует тему правильно

Правила:
- A1-A2: очень простые слова и короткие предложения
- B1-B2: добавь больше естественных примеров
- C1-C2: добавь нюанс, но кратко
- Не давай задания в конце
- Не больше 260 слов
"""

    if mode == "quiz":
        return base + """
Сделай мини-тест на 5 вопросов.

Формат:
1. Multiple choice
2. Multiple choice
3. Fill the gap
4. Translate into English
5. Correct the mistake

Правила:
- Не давай ответы заранее
- Вопросы должны соответствовать уровню ученика
- Каждый вопрос должен проверять именно эту тему
- Пиши коротко и понятно
"""

    if mode == "summary":
        return base + """
Сделай короткую шпаргалку. Это справочник, а не урок и не практика.

Формат:
1. Главное правило в 1-2 предложениях
2. 3 ключевых примера: English -> Russian
3. Мини-таблица или список форм, если подходит к теме
4. 5 полезных слов или фраз по теме с коротким переводом
5. Что запомнить

Правила:
- Без длинных объяснений
- Без заданий и вопросов
- Не больше 180 слов
"""

    return base + """
Помоги ученику разобраться в теме.
Дай короткое объяснение, 3 примера и 1 маленькое задание.
"""


def make_practice_task_prompt(topic: str, level: str) -> str:
    return f"""
Ты даешь практические задания по английскому.

Тема: {topic}
Уровень: {level}

Сделай ровно 5 коротких заданий от лёгкого к более активному.
Задания будут показываться ученику по одному, поэтому каждое задание должно быть самостоятельным.

Верни ответ строго JSON без markdown и без пояснений вокруг:
{{
  "title": "✍️ Тренировка: {topic}",
  "tasks": [
    {{
      "type": "choose",
      "question": "Choose the best option: ...",
      "options": ["...", "...", "..."],
      "correct_answer": "...",
      "acceptable_answers": ["A", "..."],
      "explanation": "коротко объясни на русском"
    }},
    {{
      "type": "fill_gap",
      "question": "Fill the gap: ...",
      "options": [],
      "correct_answer": "...",
      "acceptable_answers": ["..."],
      "explanation": "коротко объясни на русском"
    }},
    {{
      "type": "correct",
      "question": "Correct the mistake: ...",
      "options": [],
      "correct_answer": "...",
      "acceptable_answers": ["..."],
      "explanation": "коротко объясни на русском"
    }},
    {{
      "type": "rewrite",
      "question": "Rewrite this sentence using the target grammar: ...",
      "options": [],
      "correct_answer": "...",
      "acceptable_answers": ["...", "..."],
      "explanation": "коротко объясни на русском"
    }},
    {{
      "type": "build",
      "question": "Build the sentence from these words: ...",
      "options": [],
      "correct_answer": "...",
      "acceptable_answers": ["..."],
      "explanation": "коротко объясни на русском"
    }}
  ]
}}

Правила:
- Не вставляй правильный ответ в текст question или options, если это не сам вариант выбора
- correct_answer и acceptable_answers нужны боту для проверки, поэтому их обязательно заполняй
- Задания должны быть короткими
- Все задания, варианты ответа, примеры, предложения, correct_answer и acceptable_answers должны быть только на английском
- Не используй русские предложения внутри question/options/correct_answer/acceptable_answers
- Русский можно использовать только в explanation
- Задания должны проверять именно эту тему
- Ученик отвечает на каждое задание отдельно
- Для choose correct_answer должен быть текстом правильного варианта, а acceptable_answers должен включать букву A/B/C и сам текст варианта
- Для остальных заданий correct_answer должен быть коротким проверяемым ответом
- acceptable_answers должен включать 1-3 естественных варианта ответа
- Для A1-A2 используй очень простые предложения
- Не проси длинные сочинения
- Весь JSON должен быть валидным
"""


