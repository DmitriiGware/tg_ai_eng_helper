SYSTEM_TUTOR = """
Ты современный AI-репетитор английского для русскоязычного ученика.

Главная цель: дать ученику маленький, понятный шаг, который он может сразу применить.

Правила:
- Объясняй на русском.
- Английский используй в примерах, фразах, заданиях и исправленных вариантах.
- Не смешивай русский и английский внутри одной фразы без необходимости.
- Пиши дружелюбно, но без воды и длинных учебниковых лекций.
- Подстраивай сложность под уровень ученика.
- Не перегружай ответ исключениями, если ученик A1-B1.
- Если тема широкая, выбери самый полезный базовый сценарий и скажи, что это стартовая версия.
- Всегда давай естественные примеры, которые можно сказать в реальной жизни.
- Не выдумывай сложные грамматические термины, если можно объяснить проще.
"""


def make_user_prompt(topic: str, mode: str, level: str) -> str:
    topic = topic.strip()

    base = f"""
Тема: {topic}
Уровень ученика: {level}
"""

    if mode == "explain":
        return base + """
Сделай мини-урок.

Формат:
1. Что это значит
2. Когда использовать
3. Формула или простой шаблон, если тема грамматическая
4. 4 примера: English -> Russian
5. Частая ошибка
6. Мини-задание: 2 коротких пункта без ответов

Правила:
- A1-A2: очень простые слова и короткие предложения
- B1-B2: добавь больше естественных примеров
- C1-C2: добавь нюанс, но кратко
- Не больше 220 слов
"""

    if mode == "quiz":
        return base + """
Сделай мини-тест на 5 вопросов.

Формат:
1. Multiple choice
2. Multiple choice
3. Fill the gap
4. Translate into English
5. Correct the mistake

Правила:
- Не давай ответы заранее
- Вопросы должны соответствовать уровню ученика
- Каждый вопрос должен проверять именно эту тему
- Пиши коротко и понятно
"""

    if mode == "summary":
        return base + """
Сделай короткий конспект.

Формат:
1. Главное правило в 1-2 предложениях
2. 3 ключевых примера: English -> Russian
3. 5 полезных слов или фраз по теме с коротким переводом
4. Что запомнить

Правила:
- Без длинных объяснений
- Не больше 180 слов
"""

    return base + """
Помоги ученику разобраться в теме.
Дай короткое объяснение, 3 примера и 1 маленькое задание.
"""


def make_practice_task_prompt(topic: str, level: str) -> str:
    return f"""
Ты даешь практические задания по английскому.

Тема: {topic}
Уровень: {level}

Сделай ровно 5 заданий:
1. Translate into English
2. Make a sentence
3. Answer the question
4. Fill the gap
5. Correct the mistake

Формат:
🧠 Practice: {topic}

1. Translate into English:
...

2. Make a sentence:
Use these words: ...

3. Answer the question:
...

4. Fill the gap:
...

5. Correct the mistake:
...

Правила:
- Не давай ответы заранее
- Задания должны быть короткими
- Задания должны проверять именно эту тему
- Ученик должен мочь ответить одним сообщением
- Для A1-A2 используй очень простые предложения
"""


def make_practice_check_prompt(topic: str, level: str, task: str, user_answer: str, mode: str = "practice") -> str:
    return f"""
Ты проверяешь ответы ученика по английскому.

Тема: {topic}
Уровень: {level}
Тип задания: {mode}

Задание:
{task}

Ответ ученика:
{user_answer}

Проверь ответ внимательно.

Формат:
1. Результат
- Сколько примерно верно: X/5 или короткая оценка

2. Что хорошо
- 1-2 коротких пункта

3. Что исправить
- Покажи ошибку
- Дай правильный вариант
- Объясни простыми словами на русском

4. Natural version
- Дай естественный английский вариант ответа

5. Мини-повтор
- Дай 1 новое короткое задание по самой слабой ошибке

Правила:
- Не будь слишком строгим к уровню A1-A2
- Исправляй только реальные ошибки
- Если ответ верный, не придумывай проблему
- Не больше 220 слов
"""


def make_roadmap_lesson_prompt(topic: str, level: str, simplify: bool = False) -> str:
    simplify_block = ""
    if simplify:
        simplify_block = """
Объясни тему намного проще обычного.
- Используй короткие предложения
- Используй совсем простые примеры
- Практику сделай легче обычного
"""

    return f"""
Тема: {topic}
Уровень ученика: {level}

Сделай урок для плана обучения. Урок должен состоять из двух последовательных блоков теории и практики.
Теория должна быть чуть подробнее обычной: не сухое определение, а понятное объяснение с контекстом, примерами и типичными ошибками.

Верни ответ строго в таком формате:

===THEORY_1===
Объясни смысл темы простыми словами на русском.
Покажи, когда эта тема реально нужна в речи.
Дай 3-4 простых примера: English -> Russian.
Добавь короткую заметку "что важно запомнить".

===THEORY_2===
Объясни, как применять тему шаг за шагом.
Покажи формулу, шаблон или речевую конструкцию, если это подходит к теме.
Дай 2 частые ошибки и правильные варианты.
Добавь 1 мини-подсказку, как самому проверить свой ответ.

===PRACTICE===
Сделай 5 заданий:
1. Translate into English
2. Fill the gap или Correct the mistake
3. Answer the question
4. Make a sentence
5. Correct the mistake или Choose the best option

Правила:
- Пиши объяснение на русском
- Не давай правильные ответы заранее
- Практика должна проверять именно эту тему
- Ученик должен мочь ответить одним сообщением
- Для A1-A2 используй очень простые предложения
- Каждый блок теории должен быть информативным, но не длиннее 160-220 слов

{simplify_block}
"""


def make_roadmap_review_prompt(topics: list[str], level: str, simplify: bool = False) -> str:
    topics_text = ", ".join(topics)
    simplify_block = ""
    if simplify:
        simplify_block = """
Сделай повторение легче обычного.
- Используй короткие предложения
- Дай больше подсказок в заданиях
"""

    return f"""
Темы для повторения: {topics_text}
Уровень ученика: {level}

Сделай урок-повторение для плана обучения. Нужно освежить уже изученные темы и закрепить их практикой.
Теория должна быть полезной: напомни правила, покажи различия между темами и дай понятные ориентиры перед заданиями.

Верни ответ строго в таком формате:

===THEORY_1===
Напомни 3-4 главных правила по этим темам простыми словами на русском.
Дай простые примеры: English -> Russian.
Добавь короткую заметку "что повторяем".

===THEORY_2===
Покажи, чем эти темы часто путаются и как их различать.
Дай 2-3 частые ошибки и правильные варианты.
Добавь 1 мини-подсказку, как самому проверить ответ перед отправкой.

===PRACTICE===
Сделай 5 заданий на повторение:
1. Translate into English
2. Fill the gap
3. Correct the mistake
4. Answer the question
5. Make a sentence

Правила:
- Не давай ответы заранее
- Проверяй все перечисленные темы, а не только одну
- Ученик должен мочь ответить одним сообщением
- Каждый блок теории должен быть информативным, но не длиннее 160-220 слов

{simplify_block}
"""


def make_roadmap_check_prompt(topic: str, level: str, lesson: str, user_answer: str) -> str:
    return f"""
You are checking a student's English answer for a roadmap lesson.

Topic: {topic}
Level: {level}

Lesson and task:
{lesson}

Student answer:
{user_answer}

Return strictly in this format:
RESULT: correct or incorrect
FEEDBACK:
- Give a short Russian summary for each task.
- Mark each task as correct, almost correct, or incorrect.
- If there is a mistake, give the corrected English version and a short Russian explanation.
- Finish with "Итог:" and name the main thing the student should repeat.
- If most answers are correct and mistakes are minor, RESULT should be correct.
"""


def make_vocab_words_prompt(level: str, count: int, recent_words: list[str] | None = None) -> str:
    recent_block = ""
    if recent_words:
        recent_block = "Не используй эти слова повторно: " + ", ".join(recent_words)

    return f"""
Сделай ежедневную подборку слов по английскому.

Уровень ученика: {level}
Количество слов: {count}

Формат:
одна строка = слово | перевод | пример | перевод примера

Правила:
- слова должны подходить уровню
- слова должны быть полезными в повседневной речи
- не бери редкие, книжные или слишком узкие слова
- не бери одно и то же слово в разных формах
- не бери имена, бренды и топонимы
- пример должен быть коротким и естественным
- без длинных объяснений
- без нумерации
- не добавляй текст до или после списка

{recent_block}
"""
