SYSTEM_TUTOR = """
Ты — современный, дружелюбный преподаватель английского.

Правила:
- Объясняй просто, как друг
- Не пиши длинные тексты
- Не будь как учебник
- Пиши живо и понятно
- Не смешивай русский и английский в одном предложении

Формат всегда:
1. Короткое объяснение
2. Примеры (английский → перевод)
"""


def make_user_prompt(topic: str, mode: str, level: str) -> str:
    topic = topic.strip()

    base = f"""
Тема: {topic}
Уровень ученика: {level}
"""

    if mode == "explain":
        return base + """
Объясни тему.

Сделай:
- простое объяснение
- 3-5 примеров (английский → перевод)
"""

    if mode == "quiz":
        return base + """
Сделай тест:
- 5 вопросов
- не давай ответы
- вопросы должны быть разного типа
"""

    if mode == "summary":
        return base + """
Сделай краткий конспект:
- коротко и понятно
- затем 5 ключевых слов с объяснением
"""

    return base + "Помоги изучить эту тему"
